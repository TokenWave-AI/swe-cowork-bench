#!/usr/bin/env python3
"""Regenerate claude-harness/runner/sidecar_budget_sources.py for a release.

Usage:
    python3 tools/regen_sidecar_pins.py RELEASE [--from-images] [--pull]
                                        [--rows 1,2,3] [--output PATH] [--check]

The pins are expected SHA-256 values of the workplace-sidecar sources the
legacy budget patcher (runner/sidecar_budget.py) rewrites:
``/usr/local/bin/harbor_dynamic_colleague_adapter.py`` and
``/usr/local/bin/runtime_daemon.py``, plus the native-budget rows that ship
``colleague_output_budget.py``.

Sources, per row and file:
  * MANIFEST (default): ``tasks/NNN-*/environment/workplace-service/<file>`` hash
    from the release MANIFEST entry, when the task ships that file.
  * ``--from-images``: the file inside the row's digest-pinned workplace image,
    read with ``docker create`` + ``docker cp`` (the container is never started
    and is removed afterwards). Image values win; disagreements with the
    MANIFEST are reported. Images not present locally are skipped unless
    ``--pull`` is given.

The generated module records the MANIFEST SHA-256 it belongs to. At run time
pins are enforced only when that hash equals the release being evaluated;
otherwise the patcher derives expectations from the MANIFEST directly.
``--check`` exits 1 when the current pins file was generated for a different
MANIFEST (no file is written).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import pprint
import subprocess
import sys
import tempfile
import time

HERE = Path(__file__).resolve().parent
RUNNER = HERE.parent / 'runner'
COMMON = next((p for p in (HERE.parent / 'common', HERE.parent.parent / 'common') if (p / 'sidecar_manifest.py').is_file()),
              HERE.parent.parent / 'common')
sys.path.insert(0, str(COMMON))
from sidecar_manifest import (ADAPTER, NATIVE_HELPER, NOTIFICATION,  # noqa: E402
                              manifest_sha256, native_budget, sha256_file)

DEFAULT_OUTPUT = RUNNER / 'sidecar_budget_sources.py'
LABEL = 'org.cowork.eval-kit.pin-extract'


def docker(*args, check=True, timeout=600):
    return subprocess.run(['docker', *args], check=check, timeout=timeout,
                          capture_output=True, text=True)


def image_hashes(image, paths, pull):
    """Return {path: sha256 or None} read from a never-started container."""
    present = docker('image', 'inspect', image, check=False).returncode == 0
    if not present:
        if not pull:
            return None
        docker('pull', image, timeout=3600)
    created = docker('create', '--network', 'none', '--label', LABEL + '=1', image,
                     '/nonexistent-pin-extract').stdout.strip()
    try:
        result = {}
        with tempfile.TemporaryDirectory(prefix='sidecar-pins-') as directory:
            for path in paths:
                target = Path(directory) / Path(path).name
                copied = docker('cp', created + ':' + path, str(target), check=False)
                result[path] = (sha256_file(target)
                                if copied.returncode == 0 and target.is_file() and not target.is_symlink()
                                else None)
        return result
    finally:
        docker('rm', '-f', created, check=False)


def render(release_id, manifest_hash, source, adapters, notifications, natives, helpers):
    header = ('"""Sidecar source pins -- GENERATED by tools/regen_sidecar_pins.py; do not edit.\n\n'
              f'Release: {release_id}\nSource: {source}\nGenerated: {time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}\n\n'
              'Pins are enforced only when PINNED_MANIFEST_SHA256 equals the evaluated\n'
              'release MANIFEST; otherwise runner/sidecar_manifest.py derives expectations\n'
              'from the MANIFEST. Regenerate after every release rebuild:\n'
              '    python3 tools/regen_sidecar_pins.py RELEASE --from-images\n"""\n\n')
    body = [f'RELEASE_ID = {release_id!r}',
            f'PINNED_MANIFEST_SHA256 = {manifest_hash!r}',
            f'PIN_SOURCE = {source!r}',
            'EXPECTED_ADAPTER_SHA256 = ' + pprint.pformat(adapters, width=100, sort_dicts=True),
            'EXPECTED_NOTIFICATION_SHA256 = ' + pprint.pformat(notifications, width=100, sort_dicts=True),
            'NATIVE_CONFIGURED_BUDGETS = ' + pprint.pformat(natives, width=100, sort_dicts=True),
            'KNOWN_NATIVE_HELPER_SHA256 = ' + pprint.pformat(tuple(sorted(helpers)), width=100)]
    return header + '\n\n'.join(body) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('release', type=Path)
    parser.add_argument('--from-images', action='store_true')
    parser.add_argument('--pull', action='store_true', help='pull workplace images that are not present locally')
    parser.add_argument('--rows', help='comma-separated subset of rows (default: all)')
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    release = args.release.resolve(strict=True)
    manifest_path = release / 'MANIFEST.json'
    manifest_hash = sha256_file(manifest_path)
    if args.check:
        namespace = {}
        exec(compile(Path(args.output).read_text(), str(args.output), 'exec'), namespace)
        current = namespace.get('PINNED_MANIFEST_SHA256')
        print(json.dumps({'pins_manifest_sha256': current, 'release_manifest_sha256': manifest_hash,
                          'current': current == manifest_hash}))
        return 0 if current == manifest_hash else 1
    manifest = json.loads(manifest_path.read_text())
    wanted = {int(r) for r in args.rows.split(',')} if args.rows else None
    adapters, notifications, natives, helpers = {}, {}, {}, set()
    report = {'missing_images': [], 'unpinned_rows': [], 'image_manifest_mismatch': []}
    for entry in sorted(manifest['tasks'], key=lambda e: e['row']):
        row = entry['row']
        if wanted is not None and row not in wanted:
            continue
        values = {path: manifest_sha256(entry, path) for path in (ADAPTER, NOTIFICATION, NATIVE_HELPER)}
        if args.from_images:
            observed = image_hashes(entry['images']['workplace'], list(values), args.pull)
            if observed is None:
                report['missing_images'].append(row)
            else:
                for path, value in observed.items():
                    if value and values[path] and value != values[path]:
                        report['image_manifest_mismatch'].append({'row': row, 'path': path})
                    if value:
                        values[path] = value
        if values[ADAPTER]:
            adapters[row] = values[ADAPTER]
        if values[NOTIFICATION]:
            notifications[row] = values[NOTIFICATION]
        if not (values[ADAPTER] and values[NOTIFICATION]):
            report['unpinned_rows'].append(row)
        native = native_budget(entry)
        if native:
            native['files'] = {path: values[path] or digest for path, digest in native['files'].items()}
            natives[row] = native
            helpers.add(native['files'][NATIVE_HELPER])
    source = 'manifest+images' if args.from_images else 'manifest'
    args.output.write_text(render(manifest.get('release'), manifest_hash, source,
                                  adapters, notifications, natives, helpers))
    print(json.dumps({'output': str(args.output), 'release': manifest.get('release'),
                      'manifest_sha256': manifest_hash, 'source': source,
                      'adapter_rows': len(adapters), 'notification_rows': len(notifications),
                      'native_rows': sorted(natives), **report}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
